#
# 위에 순서로 진행
# 설비 고장 예측에서는 둘 중 뭐가 더 중요하냐?
# 정답은 없다. 놓치면 라인 서고, 헛경보가 잦으면 아무도 안 믿는다.
# 현장이랑 상의해서 결정. 데이터 하는 사람이 혼자 정할 일

# 정확도 96.7% vs 우리 모델 98.3% 거의 같은데 재현율은 0 vs 0.5
# 정확도만 보면 이 둘을 구별 못한다.
# 왜 이런일이? 고장이 4% 뿐이라(불균형) 정상만 맞혀도 점수가 높게 나와서
# 결론: 불균형 데이터에선 정확도를 믿지 말고 재현율 정밀도를 본다.

# =====================================================================
# 8. 임계값 — 0.5 는 절대 규칙이 아니다
# =====================================================================
