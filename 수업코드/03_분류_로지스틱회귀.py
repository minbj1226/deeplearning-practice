print("    임계값  잡음  놓침  헛경보  재현율  정밀도")
for th in [0.5, 0.3, 0.2, 0.1]:
    판정_th = (p_test >= th).astype(int)
    TP, FN, FP, TN = four_block(y_test, 판정_th)
    r = TP / (TP + FN) if TP + FN else 0
    pr = TP / (TP + FP) if TP + FP else 0
