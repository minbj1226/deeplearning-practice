# TODO: 여기에 코드를 쓰세요
def 경사하강(lr=0.1, epochs=300):
    w = 0
    b = 0

    for cnt in range(epochs):
        grad_w = (L(w + h, b) - L(w - h, b)) / (2 * h)
        grad_b = (L(w, b + h) - L(w, b - h)) / (2 * h)

        w = w - lr * grad_w
        b = b - lr * grad_b
    return w, b


