# 01에선 입력이 공기온도 '하나'였습니다. 이번엔 네 개(공기온도 회전수 토크 공구마모)를 한꺼번에 본다.
# 바뀌는 건 딱 두가지다.

# 입력 하나 -> 입력 여러 개: 예측 = w1 x 공기온도 + w2 x 회전수 + w3 x 토크 + w4 x 공구마모 + b
# 채점을 '학습에서 안 쓴 데이터'로 한다 -> 진짜 실력이 나오고, 과적합이 보인다
# 걷는 방법(경사하강, 01)은 한 글자도 안 바뀐다. 손잡이가 2개에서 5개로 늘어났을 뿐.

import os
import numpy as np
import pandas as pd

DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), "수업용데이터")
df = pd.read_csv(os.path.join(DATA, "11_설비센서_ai4i.csv"), encoding="utf-8-sig")

# =====================================================================
# 1. 입력이 여러 개면 X 는 '표' — 행 = 설비 한 대, 열 = 센서 하나
# =====================================================================

# 특징(feature) = 입력으로 쓰는 값 하나하나, 공기온도도 특징, 토크도 특징. X의 열 하나 = 특징 하나
# - 특징이 여러개인 선현회귀를 '다변수 선형회귀'라고 부른다. 이름만 길지 하는 일은 같음

# 왜 여러개를 쓰나? - 온도 하나보다 온도+회전수+마모를 같이 보면 더 잘 맞을 수 있고
#                 - 어느 센서가 진짜 중요한가를 가중치 크기로 읽을 수 있음

feature_name = ["공기온도", "회전수", "토크", "공구마모"]
X = df[feature_name].values.astype(
    float
)  # df[리스트] = 그 열들만 뽑은 표 -> .values = numpy 표
y = df["공정온도"].values.astype(float)

print("[1] X 의 모양 (행, 열):", X.shape, " y 의 모양:", y.shape)
print(
    "    1번 설비의 센서값 4개:", X[0]
)  # X[0] = 0번 행 = 첫 설비의 센서값 4개 (00 미리보기 ⑦)
print("    1번 설비의 정답:", y[0])
# 읽는 법: X는 200명의 학생의 '국 영 수 과' 점수표, y는 그 학생들의 '내신 등급' 같은 거
# 한 행이 한 학생(설비), 한 열이 한 과목(센서)

# =====================================================================
# 2. 학습용 / 시험용 나누기 — 시험 문제를 미리 보지 않기
# =====================================================================
# 01에선 200대 전부로 배우고 200대 전부로 채점했다. 이건 '답안지 보고 푼 시험'이라 점수를 믿을 수 없음
# 그래서 시작하자마자 30%를 떼어 금고에 넣고, 마지막 채점에만 꺼낸다. 학습 중엔 절대 안 봄.
# train(학습용) = 배우는데 쓰는 데이터 (교과서)
# test(시험용) = 배운 적 없는 데이터로 실력을 재는 데 쓰는 데이터 (시험지)
# 일반화 = '안 본 데이터'에서도 맞히는 능력. 우리가 진짜 원하는 것. 시험용 점수가 그 척도
# -왜냐 현장에 들어가는 순간부터 들어오는 데이터는 전부 '안 본 데이터'

rng = np.random.RandomState(
    42
)  # 무작위 기계에 번호(42)를 붙이면, 몇 번 돌려도 같은 무작위가 나옴

order = rng.permutation(len(X))  # 0~199 를 무작위로 섞은 순서표. permutation = "섞어라"

n_train = int(len(X) * 0.7)  # 200 × 0.7 = 140.0 → int() 로 소수점 버려 140
tr, te = (
    order[:n_train],
    order[n_train:],
)  # 섞은 순서의 앞 140개 번호 = 학습용, 뒤 60개 번호 = 시험용 (00 미리보기 ⑥ 슬라이스)

X_train, X_test = (
    X[tr],
    X[te],
)  # 문법 X[번호 리스트] = 그 번호의 행들만 골라 새 표를 만듦

y_train, y_test = (
    y[tr],
    y[te],
)  # 정답도 '같은 번호'로 골라야 짝이 안 어긋납니다. 이게 제일 중요.
print("\n[2] 학습용", len(tr), "대 / 시험용", len(te), "대")

# 01에서는 X가 200개 짜리 한 줄
# (200, 4)
# 설비당 답 하나 나옴

# 200 문제짜리 문제집이 있음 140문제로 공부하고,
# 나머지 60문제는 봉투에 넣어 봉인. 시험 볼 때만 뜯음
# 01 마지막에 봤다. 배운 걸 다시 물어보면 만점이 나온다.
# 실력이 아닌 기억력으로 문제 푼 것

# 파일이 날짜순이나 설비순으로 졍렬돼 있으면, 앞 140은 1월 것,
# 뒤 60은 12월 것 이런식으로 될 수 있다. 그럼 시험이 편향됨
# "현장 데이터는 거의 항상 정렬돼있음. 섞는 걸 잊지 말 것"

# 왜 7:3? 관습. 8:2도 많이 사용. 데이터가 적을수록 학습용을 더 챙긴다.

# =====================================================================
# 3. 표준화 — 열마다 따로, 그리고 학습용의 평균·표준편차만 써서
# =====================================================================
# 네 센서의 숫자 크기가 제각각. 학습용 평균을 보면:

print("\n[3] 열별 원래 크기 (학습용 평균):", X_train.mean(axis=0).round(1))
# axis=0 "세로 방향으로" = 열마다 하나씩. 4열이니 평균이 4개가 나온다 (axis=1이면 행마다)
# 온도 300, 회전수 1400, 토크 40, 마모 120 전부 다름


# 표준화 없이 그냥 걸으면 어떻게 되나 - 01 발산이 훨씬 심해진다.(손잡이가 4개라 튕길 방향도 4개)
def 손실_원래눈금(X, y, w, b):
    return np.mean((y - (X @ w + b)) ** 2)


print("    표준화 안 하고 20걸음 걸어 보기:")
for lr in [0.1, 0.0000001]:
    w0, b0 = np.zeros(4), 0.0
    for _ in range(20):
        gw = np.array(
            [
                (
                    손실_원래눈금(X_train, y_train, w0 + np.eye(4)[j] * 1e-4, b0)
                    - 손실_원래눈금(X_train, y_train, w0 - np.eye(4)[j] * 1e-4, b0)
                )
                / 2e-4
                for j in range(4)
            ]
        )
        gb = (
            손실_원래눈금(X_train, y_train, w0, b0 + 1e-4)
            - 손실_원래눈금(X_train, y_train, w0, b0 - 1e-4)
        ) / 2e-4
        w0, b0 = w0 - lr * gw, b0 - lr * gb
    print(
        f"      lr={lr:<10} → 손실 {손실_원래눈금(X_train, y_train, w0, b0):.2e}"
    )  # {:.2e} = 지수 표기 (1.18e+39 = 1.18 × 10³⁹)

# lr=0.1 -> 손실이 10의 39제곱. 발산(튕겨 나감). 회전수 1500이 곱해져 한 걸음이 너무 커서
# lr=0.0000001 -> 안 튕기긴 하는데 손실 1106. 20걸음으로는 어림도 없음
# 온도쪽은 그 lr로 너무 작아서
# 즉 '회전수에 맞는 보폭'과 '온도에 맞는 보폭'이 다른데 학습률은 하나 뿐 -> 어느 쪽에 맞춰도 망함
# 해결: 열마다 자를 똑같이 맞춘다 = 열별 표준화. 그러면 lr 하나(0.1)로 다 된다.

mu = X_train.mean(axis=0)  # 열별 평균 4개 <- 학습용으로만 계산
sd = X_train.std(axis=0)  # 열별 표준편차 4개 (퍼진 정도)
Z_train = (
    X_train - mu
) / sd  # 열마다 (값 - 그 열 평균) / 표준편차. numpy가 열 맞춰 알아서 해 준다.
Z_test = (X_test - mu) / sd  # 시험용도 '학습용의 mu, sd'로 변환

print(
    "    표준화 후 학습용 열별 평균:", np.abs(Z_train.mean(axis=0)).round(3), "← 전부 0"
)
print("    표준화 후 학습용 열별 퍼짐:", Z_train.std(axis=0).round(3), "← 전부 1")
print(
    "    표준화 후 시험용 열별 평균:",
    Z_test.mean(axis=0).round(3),
    "← 0 이 아님. 학습용 자를 빌려 썼으니 당연",
)
# 왜 시험용은 시험용 평균으로 안 하나? 두 가지 이유
# 1. 시험용 정보가 학습에 새어 들어가면(누수) 점수가 부풀려진다. "시험 문제 미리 보지 않기"의 연장선
# 현장에선 새 데이터가 한 줄씩 들어온다. 한 줄로 평균을 낼 수 없으니, 어차피 학습 때 자를 계속 써야함

# =====================================================================
# 4. 예측과 학습 — 01 과 똑같고, w 가 숫자 하나에서 '숫자 4개'가 될 뿐
# =====================================================================

# 설비 한 대의 예측 = w1 x z1 + w2 x z2 + w3 x z3 + w4 x z4 + b ("센서값에 가중치 곱해서 다 더하기")
# 이걸 140대에 대해 한 번에 쓰는 게 행렬곱 Z @ w다.
# @ = 행렬곱. "각 행에 대해, 곱해서 더하기"를 한꺼번에 (140행 x 4열) @ (4개) -> 140개
# for 문으로 140번 돌려도 같은 답이지만 @가 수백 배 빠르다.


def pred(Z, w, b):
    return Z @ w + b


def loss(Z, y, w, b):  # 01과 완전히 같음: (실제 − 예측)²의 평균 = MSE
    return np.mean((y - pred(Z, w, b)) ** 2)


# 기울기(어느 쪽이 내리막)는 01처럼 '살짝 밟아보기' 손잡이가 5개(w 4개 + b)니까 5번 밟아 본다.
# 편미분 = 손잡이 여러 개 중 '하나만' 살짝 움직였을 때 손실이 변하는 정도
# 아래 for문 한 바퀴가 편미분 한번
# 그래디언트 = 편미분 5개를 한 줄로 모은 것(gw 4개 + gb). "5개 손잡이 각각의 내리막 방향표"
h = 0.0001


def grad(Z, y, w, b):
    gw = np.zeros(len(w))
    for j in range(len(w)):  # j = 0,1,2,3 : j 번째 손잡이만 움직여 본다
        w_plus, w_minus = w.copy(), w.copy()
        w_plus[j] += h  # j 번째만 살짝 키우고
        w_minus[j] -= h  # j 번째만 살짝 줄여서
        gw[j] = (loss(Z, y, w_plus, b) - loss(Z, y, w_minus, b)) / (
            2 * h
        )  # (오른쪽 손실 − 왼쪽 손실) ÷ 거리
    gb = (loss(Z, y, w, b + h) - loss(Z, y, w, b - h)) / (2 * h)  # b 도 한 번
    return gw, gb


def train(Z, y, lr=0.1, epochs=500):
    w = np.zeros(Z.shape[1])  # Z.shape[1] = 열 수 = 4. 가중치 4개를 0 에서 출발
    b = 0.0
    for _ in range(epochs):  # 500 바퀴 (에폭 500)
        gw, gb = grad(Z, y, w, b)
        w = w - lr * gw  # 경사하강 4개라 한꺼번에 '내리막 쪽으로 보폭 lr 만큼'
        b = b - lr * gb
    return w, b


w, b = train(Z_train, y_train)  # 학습용으로만 배움
print("\n[4] 학습 완료 — 표준화 눈금의 가중치")

for name, wi in zip(feature_name, w):
    print(
        f"    {name:6s} w = {wi:+.3f}"
    )  # {:+.3f} = 부호 붙여 소수 3자리 (00 미리보기 ①)
print(f"    절편 b = {b:.3f}")

# 절편 310 = 모든 센서가 '평균값'일 때의 예측 공정온도. 표준화했으니 z=0이 평균이라 그렇다.
# 공기온도 w=+1.79 : 공기온도가 표준편차 1개만큼 오르면 공정온도가 1.79 오른다. 나머지는 거의 0.


# =====================================================================
# 5. 채점 — 학습용 점수와 시험용 점수를 '나란히'
# =====================================================================
def MSE(y, yhat):  # 손실과 같은 식. 채점용으로 이름만 따로
    return np.mean((y - yhat) ** 2)


def R2(y, yhat):  # 01 9번의 R². 1 에 가까울수록 좋음, 0 = 평균만 말하는 수준
    return 1 - np.sum((y - yhat) ** 2) / np.sum((y - y.mean()) ** 2)


tr_pred = pred(Z_train, w, b)
te_pred = pred(Z_test, w, b)
print("\n[5] 채점")
print(
    f"    학습용(train)  R² {R2(y_train, tr_pred):.4f}   손실 {MSE(y_train, tr_pred):.3f}"
)
print(
    f"    시험용(test)   R² {R2(y_test, te_pred):.4f}   손실 {MSE(y_test, te_pred):.3f}"
)
# 학습용 0.81, 시험용0.78

print("""
    읽는 법 — 두 점수를 '같이' 봐야 합니다:
      둘이 비슷하고 둘 다 좋음        → 건강. 규칙을 배운 것
      학습용만 좋고 시험용이 뚝 떨어짐  → 과적합. 답안지를 외운 것
      둘 다 나쁨                     → 과소적합. 모델이 너무 단순하거나 센서가 부족
    어림 기준: R² 차이가 0.05 안이면 정상, 0.10 넘으면 의심. (법칙은 아니고 경보선)
""")
# 과적합 - 학습 데이터를 '외워서' 학습 점수는 좋은데 새 데이터엔 틀리는 상태
#       - 기출문제만 달달 외운 학생. 모의고사(학습용) 100점, 수능(시험용) 60점
#       - 과적합이 나면 -> 현장에 넣은 순간 점수가 무너진다. 학습 점수만 보고 사고 나는 상황

# 과소적합 - 덜 배워서 학습 점수부터 나쁜 상태.
#         - 과소적합이 나면 -> 아예 못 맞힌다. 센서를 더 넣거나, 더 오래 걷거나, 더 유연한 모델이 필요
# 왜 굳이 시험용을 따로 보나? 학습 점수는 '외웠는지 배웠는지' 구별을 못함. 시험용만이 구별해줌

print("    시험용 앞 6대: 예측 vs 실제")
for p, t in zip(te_pred[:6], y_test[:6]):
    print(f"      예측 {p:7.2f}   실제 {t:7.2f}   (차이 {t - p:+.2f})")


