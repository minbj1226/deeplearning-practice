# 5-1. 과적합을 눈으로 — 학습용을 딱 5대만 주면?
# =====================================================================
# 손잡이는 5개(w 4개 + b)인데 데이터가 5대면, 5대를 완벽히 지나는 답이 존재. 외우기가 가능

print("[5-1] 학습용을 5대만 써서 학습하면? (손잡이 5개 = 데이터 5대)")
w5, b5 = train(Z_train[:5], y_train[:5], epochs=2000)
print(
    f"    학습용 5대 R² {R2(y_train[:5], pred(Z_train[:5], w5, b5)):.4f}   ← 만점. 5대를 통째로 외웠다"
)
print(
    f"    시험용 60대 R² {R2(y_test, pred(Z_test, w5, b5)):.4f}   ← 140대로 배웠을 때(0.78)보다 뚝. 이게 과적합"
)
print("    가중치도 달라짐:", w5.round(2), "← 140대 때는", w.round(2))

