# =====================================================================
#  01. 경사하강을 손으로 — 공기온도로 공정온도 맞히기
#  실행: python 01_numpy_경사하강_직접구현.py   (수업코드 폴더에서)
# =====================================================================

import os
import numpy as np
import pandas as pd

DATA = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "수업용데이터"
)  # data/수업용데이터/
df = pd.read_csv(os.path.join(DATA, "11_설비센서_ai4i.csv"), encoding="utf-8-sig")

x = df["공기온도"].values.astype(
    float
)  # 입력: 설비 200대의 공기온도. astype(float) = 전부 실수형으로 (정수 섞임 방지)
y = df["공정온도"].values.astype(float)  # 정답: 그 설비의 공정온도
print(
    "설비",
    len(x),
    "대 / 공기온도",
    x.min(),
    "~",
    x.max(),
    "/ 공정온도",
    y.min(),
    "~",
    y.max(),
)
print("앞 5대  공기온도:", x[:5])
print("앞 5대  공정온도:", y[:5])

# 눈으로 보면 공정온도는 공기온도보다 대략 10 정도 높습니다. 그 '대략'을 정확한 숫자로 찾는게 오늘 목표

# =======================================================================================
# 1. 예측은 직선 하나 - 숫자 두개로 결정
# =======================================================================================
# 예측 공정온도 = w x 공기온도 + b
# w = 공기온도가 1 오를 때 공정온도가 얼마나 오르나 (기울기)(가중치)
# b = 그냥 더해 주는 값 (보정값)

# 선형모델 = "입력에 숫자(w)를 곱하고 숫자(b)를 더해서" 답을 내는 모델. 그래프로 그리면 직선
# 가장 단순하지만, 어느 입력이 얼마나 영향을 주는지(w)를 읽을 수 있어서 현장에서 사랑받음.

# 선형회귀 = 선형모델로 '숫자'를 맞히는 것. 오늘 하는 일이 바로 선형회귀
# 회귀 = 맞히려는 답이 '숫자'인 문제. 공정온도 308.8처럼 연속된 값


def pred(x, w, b):
    return w * x + b  # x가 배열이면 200개가 한꺼번에 계산된다. (numpy의 장점)


print("\n[1] 일단 감으로 w=1, b=10을 넣어 본다 ('공정온도 = 공기온도 + 10')")
print("   예측 (앞 5대):", pred(x, 1.0, 10.0)[:5])
print("   실제 (앞 5대):", y[:5])

# 비슷한데 조금씩 틀리다. '조금씩'이 얼마인지 숫자 하나로 재야 비교 가능

# ===================================================================
# 2. 손실 - 틀린 정도를 점수 하나로 (작을수록 좋음)
# ===================================================================
# 방법: (실제 - 예측)을 200대 각각 구해 -> 제곱해서 -> 평균 낸다.
# 제곱하는 이유 1) -3 틀림과 +3 틀림이 더해져 0이 되는 걸 막으려고
#             2) 크게 틀린 건 더 크게 벌주려고
# 손실 = 얼마나 틀렸나를 나타내는 점수 하나. 작을수록 좋음
# MSE(평균제곱오차) = 오늘 쓰는 손실. "틀린 정도를 제곱해서 평균" 낸 것. 회귀에서 제일 흔한 자


def error(x, y, w, b):
    error_degree = y - pred(x, w, b)  # 설비마다 (실제 - 예측)
    return np.mean(error_degree**2)  # 제곱해서 평균. **2 = 제곱


print("\n[2] 여러 직선의 손실 점수")
for w, b in [(1.0, 10.0), (1.0, 9.0), (1.0, 11.0), (0.0, 310.0)]:
    print(f"    w={w}, b={b:<5} → error {error(x, y, w, b):.4f}")

# =====================================================================
# 3. 어느 쪽으로 고칠까 - 살짝 바꿔 보고 손실을 다시 잰다
# =====================================================================
# 안개 낀 언덕에서 내려갈 때 하는 일: 왼발 오른발로 땅을 밟아보고 낮은 쪽으로 간다
# 손잡이 하나(b)를 아주 조금 키워보고 / 줄여보고, 손실이 어느 쪽에서 작아지는지 보자.
# (w는 잠깐 1.0으로 고정)
print("\n[3] b 를 살짝 밟아보기 (w=1.0 고정, 지금 b=9.0 이라고 치고)")
print(f"    b=8.9 → 손실 {error(x, y, 1.0, 8.9):.4f}")
print(f"    b=9.0 → 손실 {error(x, y, 1.0, 9.0):.4f}   ← 지금 자리")
print(f"    b=9.1 → 손실 {error(x, y, 1.0, 9.1):.4f}")
# b를 키우면(9.1) 손실이 줄고, 줄이면(8.9)늡니다 -> "b를 키우는 쪽이 내리막"
#
# 이 '밟아보기'를 숫자 하나로 요약한게 기울기
# 기울기 = (오른쪽 손실 - 왼쪽 손실) / (오른쪽과 왼쪽 사이 거리)
# 양수(+) -> 오른쪽이 오르막 -> 손잡이를 줄여라
# 음수(-) -> 오른쪽이 내리막 -> 손잡이를 키워라
# 0 근처 -> 양쪽이 평평 = 바닥 = 도착
#
# 미분 = "손잡이를 아주 조금 돌리면 손실이 얼마나, 어느 쪽으로 변하나"를 숫자 하나로 만든 것
# 방급 우리가 한 밟아보기가 그것이다. 공식이 아니라 '살짝 밀어 보고 재기'로 이해하면 충분
#
# 편미분 = "손잡이가 여러 개(w, b)일 때, 나머지는 그대로 두고 '하나만' 돌려본 미분."
# b만 돌린게 b의 편미분, w만 돌린게 w의 편미분. '손잡이별 기울기'라는 뜻

# 그래디언트 = 그 편미분들을 (w방향, b방향) 한 묶음으로 모은 것 = "어느 쪽이 오르막인지 가리키는 화살표"
# 왜 필요? 손잡이가 2개든 200개든, 각각 어느 쪽으로 돌려야 손실이 줄지 알아야 하니깐
h = 0.0001  # 아주 살짝만 밟는다(보폭) (크게 밟으면 지금 자리가 아닌 엉뚱한 곳을 제게 됨)


def grad(x, y, w, b):
    # w만 밀어본 기울기 (w의 편미분)
    gw = (error(x, y, w + h, b)) - (error(x, y, w - h, b)) / (2 * h)

    # b만 밀어본 기울기 (b의 편미분)
    gb = error(x, y, w, b + h) - error(x, y, w, b - h) / (2 * h)
    return gw, gb  # 둘을 묶어서 돌려줌 = 그래디언트


gw, gb = grad(x, y, 1, 10)
print("\n   w=1.0, b=9.0에서 b 방향 기울기 = {gb:.3f} (음수 -> b를 키워라)")
print("\n                   w 방향 기울기 = {gw:.3f} (음수 -> w도 키워라)")

# w 방향 기울기가 b보다 300배쯤 크다. 공기온도가 300 근처의 큰 숫자라 w를 조금만 건드려도
# 예측이 크게 흔들리기 때문. 이 '민감함'이 곧 큰 문제를 일으킴.

# ===========================================================================
# 4. 한 걸음 내려가기 - 규칙은 딱 한 줄
# ===========================================================================
# 새 w = 지금 w - 학습률 x 기울기 (b도 똑같이)
# '빼는'이유: 기울기 +면 줄여야 하고, -면 키워야 하는데 음수를 빼면 커진다. 부호가 알아서 방향 맞춤

# 경사하강 = 기울기(오르막 방향)의 '반대'로 조금씩 걸어 손실이 가장 낮은 곳을 찾는 방법.
#            경사(기울기)를 따라 하강(내려간다). 이름 그대로이다.

# 학습률(lr) = 한 걸음의 크기(보폭). 우리가 정하는 값. 기울기가 -600처럼 크면 그대로 뺐다간
#             너무 멀리 뛰니깐, 작은 수를 곱해 조심조심 걷는다.
# 왜 이렇게 하냐? 손실이 가장 작은 w, b가 '가장 잘 맞는 직선'인데, 그걸 한번에 아는 공식이 없는
# 문제가 대부분이라, 걸어서 찾아가는 방법을 익혀 둔다.
lr = 0.000001
w, b = 1.0, 9.0
print("\n[4] 한 걸음 (lr=0.00001)")
print(f"    이전: w={w:.5f}, b={b:.5f}, 손실 {error(x, y, w, b):.4f}")
w = w - lr * gw
b = b - lr * gb
print(
    f"    이후: w={w:.5f}, b={b:.5f}, 손실 {error(x, y, w, b):.4f}   ← 줄었죠? 이걸 반복하면 됩니다"
)

# 손실이 줄어드는 걸 계속 반복함 한번이 한걸음
# 그리고 학습이라는 건
# 이 한 걸음을 300번 반복하는게 전부다.
# 그런데 보폭이 0.00001 이렇게 걸으면 바닥까지 몇만 걸음이 걸린다. 그렇다고 보폭을 엄청 크게 키우면 늘어남

# ================================================================
# 5. 걸음이 튕기는 문제 - 표준화 (이걸 빼면 실패)
# ================================================================
# 공기온도가 300 근처의 큰 숫자라 w 방향 기울기가 너무 커서, 보폭을 조금만 키워도 튕겨 나간다.
# 일부러 실패해본다.
w, b = 1.0, 9.0
with np.errstate(over="ignore", invalid="ignore"):
    for _ in range(20):
        gw, gb = grad(x, y, w, b)
        w, b = w - 0.001 * gw, b - 0.001 * gb
print(
    "\n[5] 보폭을 0.001 로 키워 20걸음 → 손실:",
    error(x, y, w, b),
    "← 숫자가 폭발(발산)",
)
# 발산 = 걸음이 너무 커서 골짜기를 넘어 반대편으로, 다시 그 반대편으로... 점점 튕겨 나가 손실이 무한대가 된다.
# 해결 : 입력을 '평균 0, 퍼짐 1' 크기로 바꿔준다.
# z = (x - 평균) / 표준편차 -> 300 근처 숫자가 -2 ~ +3 사이의 얌전한 숫자가 된다. 정보는 그대로 눈금만 바꾼 것
# 표준화 = 값에서 평균을 빼고 표준편차로 나눠, 어떤 데이터든 비슷한 크기 (대략 -3 ~ +3)로 맞추는 것.
# 왜 하냐? 숫자가 크면 걸음이 튕기고(발산), 나중에 여러 센서를 쓸 때 단위가 달라 공평하지 않아서,
# 경사하강 전에 거의 항상 한다.

m = x.mean()  # 평균
s = x.std()  # 표준편차 (퍼진 정도)
z = (x - m) / s
print(f"    표준화: 평균 {m:.2f}, 표준편차 {s:.2f}")
print(f"    x 앞 3개: {x[:3]}  →  z 앞 3개: {z[:3].round(3)}")

# 평균을 빼고 표준편차로 나눈 얌전한 숫자로 만듦
# 평균이면 0, 평균보다 한칸 위면 1 이라는 새 눈금으로 바꾼 것

# ==================================================================
# 경사하강 완성 - 한 걸음을 반복하면 바닥에 닿는다
# ==================================================================
# 학습(fit) = 데이터를 보고 w, b를 찾는 일 = 아래 함수가 하는 일. 사이킷런의 .fit()도 이것
# 에폭(epoch) = 데이터 전체를 한 번 흝고 w, b를 한 번 고친 것. 300 에폭 = 300 걸음


def train(z, y, lr=0.1, epochs=300, show=True):
    w, b = 0.0, 0.0  # 아무데서나 출발해도 된다 (여기선 0)
    for epoch in range(epochs):
        gw, gb = grad(z, y, w, b)  # 어느 쪽이 내리막?
        w = w - lr * gw  # 그 쪽으로 한걸음
        b = b - lr * gb

        if show and epoch in (0, 1, 2, 5, 10, 30, 100, 299):
            print(
                f"    epoch {epoch:3d}  w={w:7.3f}  b={b:8.3f}  손실 {error(z, y, w, b):10.4f}"
            )  # 자릿수 지정은 00 미리보기 ①
    return w, b


print("\n[6] 경사하강 (표준화한 z 로, lr=0.1)")
w_z, b_z = train(z, y)

# 읽는 법: 출발점이 w=0, b=0이라 처음 손실이 6만 처럼 크게 나오는게 정상
# 손실이 처음엔 확 줄었다가 어느 순간 안 변한다. = 바닥 = 도착

# z눈금에서 찾은 직선을 원래 온도 눈금으로 되돌린다.
w_gd = w_z / s
b_gd = b_z - w_z * m / s
print(f"\n    결과: 공정온도 ≈ {w_gd:.4f} × 공기온도 + {b_gd:.4f}")
print(
    f"    손실: {error(x, y, w_gd, b_gd):.4f}  (감으로 넣은 (1, 10) 은 0.8941 → 0.8921. 감이 꽤 좋았던 셈이죠)"
)

# 근데 센서가 4개, 10개가 되면 감으로는 절대 못 찾는다. 그때부터가 진짜이다.


# =====================================================================
# 7. 학습률(보폭) 실험 — 너무 크면? 너무 작으면?
# =====================================================================
print("\n[7] 보폭(lr)을 바꿔 300걸음 후 손실")
for lr in [0.001, 0.01, 0.1, 1.05]:
    w_t, b_t = train(z, y, lr=lr, show=False)
    L = error(z, y, w_t, b_t)
    if np.isnan(L) or L > 1e6:  # np.isnan = "숫자가 아님(폭발)" 인가
        judge = "발산 (튕겨 나감)"
    elif L > 1.0:
        judge = "굼벵이 (300걸음으론 아직 멀었음)"
    else:
        judge = "좋음 (바닥)"
    print(f"    lr={lr:<6} → 손실 {L:>14.4f}  {judge}")

# 결론:
# 너무 작으면(0.0001) 300걸음으론 못 내려온다 -> 걸음 수를 훨씬 늘려야 함 (시간 낭비)
# 너무 크면(1.05) 튕겨 나간다(발산) -> 아예 답을 못 얻음
# 적당하면(0.1) 금방 바닥. 정답 공식은 없고, 이렇게 몇 개 넣어보고 고른다.


# =====================================================================
# 8. 정말 맞게 찾았나 — 공식과 대조
# =====================================================================
w_공식 = np.sum((x - x.mean()) * (y - y.mean())) / np.sum((x - x.mean()) ** 2)
b_공식 = y.mean() - w_공식 * x.mean()
print("\n[8] 대조")
print(f"    걸어서   w={w_gd:.4f}  b={b_gd:.4f}")
print(f"    공식으로 w={w_공식:.4f}  b={b_공식:.4f}")
print(
    "    같은가? ", abs(w_gd - w_공식) < 1e-3 and abs(b_gd - b_공식) < 1e-3
)  # 소수 셋째 자리까지 같으면 True

# 그럼 왜 걷는 법을 배웠나? 선형회귀엔 공식이 있지만
# 분류(로지스틱)부터는 공식이 없다. 그런 문제에선 오직 '걷기'만 통함
# 답을 아는 문제로 걷는 법을 익혀 두면, 답을 모르는 문제에서도 같은 걸음으로 갈 수 있다.

# =====================================================================
# 9. 써먹기 — 새 공기온도의 공정온도 예측, 그리고 점수
# =====================================================================
print("\n[9] 예측")
for 새온도 in [298.0, 300.0, 303.0]:
    print(f"    공기온도 {새온도} → 예측 공정온도 {pred(새온도, w_gd, b_gd):.2f}")

# 알제곱 (설명력) = 얼마나 잘 맞나를 0~1 점수로. 1이면 완벽, 0이면 '그냥 평균으로 찍기'와 같은 수


def R2(x, y, w, b):
    못맞힌것 = np.sum((y - pred(x, w, b)) ** 2)  # 직선이 못 맞힌 만큼
    평균으로찍기 = np.sum((y - y.mean()) ** 2)  # 그냥 평균으로 답했을 때 틀린 만큼
    return 1 - 못맞힌것 / 평균으로찍기


r2 = R2(x, y, w_gd, b_gd)
print(
    f"    R² = {r2:.4f}  ← 공정온도의 흩어짐 중 약 {r2 * 100:.0f}% 를 공기온도 하나로 설명"
)

# 함정 이 0.7989는 '본 문제로 채점한 점수'다. 학습에 쓴 200대 그대로 다시 채점
# 이 점수가 얼마나 쉽게 부풀려지는지 본다. 설비를 딱 2대만 주고 배운다.
